/**
 * Turns tools/code-video/kit/cv-kit.js (the motion kit's source of truth) into shared/code-craft/kit-source.ts,
 * a plain string the server and the browser can both inline into pages. Run after editing the kit: pnpm kit:build
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = readFileSync(join(root, "tools/code-video/kit/cv-kit.js"), "utf8");
if (/<\/script/i.test(src)) throw new Error("cv-kit.js must not contain a closing script tag: it is inlined into <script>");
const version = /version:\s*"([\d.]+)"/.exec(src)?.[1];
if (!version) throw new Error("cv-kit.js: version string not found");
const out = `/* Generated by scripts/build-cv-kit.mjs from tools/code-video/kit/cv-kit.js — edit that file, then run \`pnpm kit:build\`. */
export const CV_KIT_VERSION = ${JSON.stringify(version)};
export const CV_KIT_SOURCE = ${JSON.stringify(src)};
`;
writeFileSync(join(root, "shared/code-craft/kit-source.ts"), out);
console.log(`cv-kit ${version}: ${(src.length / 1024).toFixed(1)} KB → shared/code-craft/kit-source.ts`);
